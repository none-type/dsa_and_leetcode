
# Understand square roots, and squares before attempting.
# what is integer overflow?

#     Square: Take a number and multiply it by itself (e.g., 3 → 9).

#     Square root: Reverse it—find what number was multiplied by itself to get that result (9 → 3).

#     Power of 2: Start with 2 and multiply it repeatedly (2 → 4 → 8 → 16...).

#     Log₂: Reverse it—ask “how many times did I multiply by 2 to get here?” (16 → 4, because 2×2×2×2 = 16).

# So:
# Square/square root are about one number times itself.
# Power/log are about how many times you multiply 2.

# Both are pairs of “do” and “undo.”